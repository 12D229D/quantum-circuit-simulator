/**
 * QUANTUM CIRCUIT CODE EXPORTER
 * Generates OpenQASM 2.0, Qiskit Python, and JSON formats.
 */

class CircuitExporter {
    static toQASM(circuit) {
        const n = circuit.numQubits;
        let qasm = `OPENQASM 2.0;\ninclude "qelib1.inc";\n\nqreg q[${n}];\ncreg c[${n}];\n\n`;

        // Initialize state if not all |0>
        for (let q = 0; q < n; q++) {
            if (circuit.initialState[q] === 1) {
                qasm += `x q[${q}]; // Init |1>\n`;
            }
        }

        for (let s = 0; s < circuit.numSteps; s++) {
            for (let q = 0; q < n; q++) {
                const gate = circuit.grid[q][s];
                if (!gate) continue;

                switch (gate.type) {
                    case 'H': qasm += `h q[${q}];\n`; break;
                    case 'X': qasm += `x q[${q}];\n`; break;
                    case 'Y': qasm += `y q[${q}];\n`; break;
                    case 'Z': qasm += `z q[${q}];\n`; break;
                    case 'S': qasm += `s q[${q}];\n`; break;
                    case 'SDG': qasm += `sdg q[${q}];\n`; break;
                    case 'T': qasm += `t q[${q}];\n`; break;
                    case 'TDG': qasm += `tdg q[${q}];\n`; break;
                    case 'RX': qasm += `rx(${gate.theta || 0}) q[${q}];\n`; break;
                    case 'RY': qasm += `ry(${gate.theta || 0}) q[${q}];\n`; break;
                    case 'RZ': qasm += `rz(${gate.theta || 0}) q[${q}];\n`; break;
                    case 'CNOT':
                    case 'CX':
                        qasm += `cx q[${gate.control}], q[${q}];\n`;
                        break;
                    case 'CZ':
                        qasm += `cz q[${gate.control}], q[${q}];\n`;
                        break;
                    case 'SWAP':
                        qasm += `swap q[${gate.control}], q[${q}];\n`;
                        break;
                    case 'TOFFOLI':
                    case 'CCNOT':
                        qasm += `ccx q[${gate.control}], q[${gate.control2}], q[${q}];\n`;
                        break;
                }
            }
        }

        qasm += `\nmeasure q -> c;\n`;
        return qasm;
    }

    static toQiskitPython(circuit) {
        const n = circuit.numQubits;
        let py = `"""\nGenerated by Quantum Circuit Simulator (Codex Monorepo)\nTarget: Qiskit 1.0+ / Python 3.10+\n"""\n\n`;
        py += `from qiskit import QuantumCircuit\nfrom qiskit_aer import AerSimulator\nimport matplotlib.pyplot as plt\n\n`;
        py += `# Create Quantum Circuit with ${n} qubits\nqc = QuantumCircuit(${n}, ${n})\n\n`;

        // Initialize state if needed
        for (let q = 0; q < n; q++) {
            if (circuit.initialState[q] === 1) {
                py += `qc.x(${q})  # Init |1>\n`;
            }
        }

        for (let s = 0; s < circuit.numSteps; s++) {
            for (let q = 0; q < n; q++) {
                const gate = circuit.grid[q][s];
                if (!gate) continue;

                switch (gate.type) {
                    case 'H': py += `qc.h(${q})\n`; break;
                    case 'X': py += `qc.x(${q})\n`; break;
                    case 'Y': py += `qc.y(${q})\n`; break;
                    case 'Z': py += `qc.z(${q})\n`; break;
                    case 'S': py += `qc.s(${q})\n`; break;
                    case 'SDG': py += `qc.sdg(${q})\n`; break;
                    case 'T': py += `qc.t(${q})\n`; break;
                    case 'TDG': py += `qc.tdg(${q})\n`; break;
                    case 'RX': py += `qc.rx(${gate.theta || 0}, ${q})\n`; break;
                    case 'RY': py += `qc.ry(${gate.theta || 0}, ${q})\n`; break;
                    case 'RZ': py += `qc.rz(${gate.theta || 0}, ${q})\n`; break;
                    case 'CNOT':
                    case 'CX':
                        py += `qc.cx(${gate.control}, ${q})\n`;
                        break;
                    case 'CZ':
                        py += `qc.cz(${gate.control}, ${q})\n`;
                        break;
                    case 'SWAP':
                        py += `qc.swap(${gate.control}, ${q})\n`;
                        break;
                    case 'TOFFOLI':
                    case 'CCNOT':
                        py += `qc.ccx(${gate.control}, ${gate.control2}, ${q})\n`;
                        break;
                }
            }
        }

        py += `\n# Measure all qubits\nqc.measure(range(${n}), range(${n}))\n\n`;
        py += `# Simulate on Aer\nsimulator = AerSimulator()\nresult = simulator.run(qc, shots=1024).result()\ncounts = result.get_counts()\n`;
        py += `print("Measurement Results (1024 shots):", counts)\n`;

        return py;
    }

    static toJSON(circuit) {
        return JSON.stringify({
            version: '1.0.0',
            numQubits: circuit.numQubits,
            numSteps: circuit.numSteps,
            initialState: circuit.initialState,
            grid: circuit.grid
        }, null, 2);
    }
}

window.CircuitExporter = CircuitExporter;
